// k：名詞（查 GLOSSARY）；tip：直接給說明（優先）；children：顯示的文字，沒給就顯示 k
// 外觀不變，滑鼠移上去（手機上點一下）才顯示說明
const Term = ({ k, tip, children }) => {
  const text = tip ?? GLOSSARY[k]
  const label = children ?? k
  if (!text) return <>{label}</>
  return (
    <Tooltip
      title={text}
      placement="bottom-start"
      enterDelay={300}
      enterTouchDelay={0}
      leaveTouchDelay={6000}
      slotProps={{ tooltip: { sx: TIP_SX } }}
    >
      <span>{label}</span>
    </Tooltip>
  )
}

export default Term
